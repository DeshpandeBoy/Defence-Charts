import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'

const TARGET = fileURLToPath(
  new URL('../packages/tokens/src/themes/typography.css', import.meta.url),
)

const ROLE_STYLES = [
  ['title', 'A', 'A'],
  ['subtitle', 'B', 'D'],
  ['axis-title', 'B', 'B'],
  ['legend-label', 'C', 'C'],
  ['label', 'D', 'D'],
  ['value-label', 'E', 'A'],
  ['annotation', 'E', 'E'],
  ['crosshair-label', 'D', 'D'],
]

/** @param {import('../packages/core/src/text.ts').FittingTypography} typography */
export function renderTypographyCss(typography) {
  const lines = [
    '/* @generated by scripts/generate-typography-css.mjs — do not edit by hand. */',
    ':where(:root) {',
    `  --gx-font-family: ${typography.family};`,
    `  --gx-font-feature-settings: ${typography.featureSettings};`,
    `  --gx-font-stretch: ${typography.stretch};`,
    `  --gx-font-optical-sizing: ${typography.opticalSizing};`,
    `  --gx-numeric-variant: ${typography.featureSettings === 'normal' ? 'normal' : 'tabular-nums'};`,
  ]

  for (const [role, sizeRank, weightRank] of ROLE_STYLES) {
    const sizeStyle = typography.byRank[sizeRank]
    const weightStyle = typography.byRank[weightRank]
    lines.push(
      `  --gx-${role}-font-size: ${sizeStyle.fontSize}px;`,
      `  --gx-${role}-font-weight: ${weightStyle.fontWeight};`,
      `  --gx-${role}-letter-spacing: ${sizeStyle.letterSpacing}px;`,
    )
  }

  return `${lines.join('\n')}\n}\n`
}

async function loadBuiltDefault() {
  const built = new URL('../packages/core/dist/text.js', import.meta.url)
  return import(built.href)
    .then((module) => module.DEFAULT_TYPOGRAPHY)
    .catch(() => {
      throw new Error('Build @gx/core before checking generated typography CSS.')
    })
}

const invokedDirectly =
  process.argv[1] !== undefined && import.meta.url === new URL(`file://${process.argv[1]}`).href

if (invokedDirectly) {
  const expected = renderTypographyCss(await loadBuiltDefault())
  if (process.argv.includes('--write')) {
    await writeFile(TARGET, expected)
    console.log('typography CSS: generated.')
  } else {
    const actual = await readFile(TARGET, 'utf8').catch(() => '')
    if (actual !== expected) {
      console.error('typography CSS is stale — run `pnpm generate:typography`.')
      process.exit(1)
    }
    console.log('typography CSS: generated output is current.')
  }
}